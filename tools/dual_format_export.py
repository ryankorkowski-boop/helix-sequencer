"""Orchestrate a completed AC-only XSQ and a mapped legacy LMS export.

The source XSQ must already be generated by the normal Helix pipeline.
LMS requires a user-approved channel map. No pixel-to-AC approximation is made.
"""
from __future__ import annotations

from pathlib import Path
import shutil
import argparse
import json

from core.show_export_request import ShowExportRequest, export_selected
from tools.legacy_lms_export import export_legacy_lms, read_lor_map


def export_from_xsq(
    source_xsq: Path,
    destination: Path,
    *,
    output_format: str,
    mapping_csv: Path | None = None,
) -> dict[str, Path]:
    source_xsq = Path(source_xsq)
    if not source_xsq.is_file() or source_xsq.stat().st_size == 0:
        raise FileNotFoundError(f"Generated XSQ not found: {source_xsq}")
    request = ShowExportRequest(output_format=output_format, layout_variant="band")
    sidecar = Path(destination) / 'Performance.lms_validation.json'
    if 'lms' in request.requested_formats and sidecar.exists():
        raise FileExistsError(f'Existing LMS validation sidecar must not be overwritten: {sidecar}')
    if "lms" in request.requested_formats:
        if mapping_csv is None:
            raise ValueError("LMS requires a verified LOR controller mapping CSV")
        mapping_csv = Path(mapping_csv)
        read_lor_map(mapping_csv)  # fail before copying anything

    def xsq_export(analysis, path, req):
        if source_xsq.resolve() == path.resolve():
            raise ValueError("Source XSQ must not be overwritten")
        shutil.copyfile(source_xsq, path)

    def lms_export(analysis, path, req):
        export_legacy_lms(source_xsq, mapping_csv, path)

    exporters = {"xsq": xsq_export}
    if mapping_csv is not None:
        exporters["lms"] = lms_export
    try:
        return export_selected(request, exporters, source_xsq, destination)
    except Exception:
        if sidecar.is_file():
            sidecar.unlink()
        raise

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source_xsq', type=Path)
    parser.add_argument('destination', type=Path)
    parser.add_argument('--format', dest='output_format', choices=('xsq', 'lms', 'both'), required=True)
    parser.add_argument('--channel-map', type=Path)
    args = parser.parse_args(argv)
    results = export_from_xsq(args.source_xsq, args.destination, output_format=args.output_format, mapping_csv=args.channel_map)
    print(json.dumps({key: str(value) for key, value in results.items()}, indent=2))
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
