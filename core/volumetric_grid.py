"""Opt-in city-block volumetric grid geometry and bounded spatial sampling.

No controller universes or xLights model are generated by this module.
Coordinates remain independent from serpentine physical wiring order.
"""
from dataclasses import dataclass
from math import ceil, cos, exp, hypot, pi, sin
from typing import Iterator


@dataclass(frozen=True)
class VolumetricGrid:
    width_ft: float = 300.0
    depth_ft: float = 300.0
    height_ft: float = 4.0
    spacing_in: float = 16.0
    zone_poles: int = 8

    def __post_init__(self) -> None:
        if min(self.width_ft, self.depth_ft, self.height_ft, self.spacing_in) <= 0:
            raise ValueError("All dimensions and spacing must be positive")
        if self.zone_poles < 1:
            raise ValueError("zone_poles must be positive")

    @property
    def shape(self) -> tuple[int, int, int]:
        # Endpoints only exist where the dimension is an exact spacing multiple.
        step = self.spacing_in / 12.0
        return (int(self.width_ft / step + 1e-9) + 1,
                int(self.depth_ft / step + 1e-9) + 1,
                int(self.height_ft / step + 1e-9) + 1)

    @property
    def pixel_count(self) -> int:
        x, y, z = self.shape
        return x * y * z

    @property
    def zone_count(self) -> tuple[int, int]:
        x, y, _ = self.shape
        return ceil(x / self.zone_poles), ceil(y / self.zone_poles)

    def xyz_ft(self, x: int, y: int, z: int) -> tuple[float, float, float]:
        nx, ny, nz = self.shape
        if not (0 <= x < nx and 0 <= y < ny and 0 <= z < nz):
            raise IndexError("pixel outside grid")
        step = self.spacing_in / 12.0
        return x * step, y * step, z * step

    def zone_wiring(self, zone_x: int, zone_y: int) -> Iterator[tuple[int, int, int]]:
        """Yield one zone in pole-row serpentine order, alternating vertical direction.

        A controller designer must still split outputs by capacity and add power feeds.
        """
        zx, zy = self.zone_count
        if not (0 <= zone_x < zx and 0 <= zone_y < zy):
            raise IndexError("zone outside grid")
        nx, ny, nz = self.shape
        x0, y0 = zone_x * self.zone_poles, zone_y * self.zone_poles
        pole_index = 0
        for local_y, y in enumerate(range(y0, min(y0 + self.zone_poles, ny))):
            xs = list(range(x0, min(x0 + self.zone_poles, nx)))
            if local_y % 2:
                xs.reverse()
            for x in xs:
                zs = range(nz) if pole_index % 2 == 0 else range(nz - 1, -1, -1)
                for z in zs:
                    yield x, y, z
                pole_index += 1

    def iter_zone_pixels(self, zone_x: int, zone_y: int) -> Iterator[tuple[int, int, int]]:
        yield from self.zone_wiring(zone_x, zone_y)


def sample_spatial_intensity(
    xyz: tuple[float, float, float], grid: VolumetricGrid,
    *, time_s: float, motif: str = "wave_sweep", energy: float = 0.5,
) -> float:
    """Deterministic bounded 0..1 spatial field, compatible with Birdsong motif names.

    This is a preview/sampling primitive, not a validated Birdsong runtime integration.
    """
    x, y, z = xyz
    u, v, w = x / grid.width_ft, y / grid.depth_ft, z / grid.height_ft
    energy = max(0.0, min(1.0, energy))
    if motif == "wave_sweep":
        value = (1.0 + sin(2 * pi * (u * 3 + w - time_s * 0.5))) / 2
    elif motif == "pulse_cascade":
        radius = hypot(u - 0.5, v - 0.5)
        value = (1.0 + cos(2 * pi * (radius * 5 - time_s * 0.7))) / 2
    elif motif in ("spiral", "orbit"):
        angle = __import__("math").atan2(v - 0.5, u - 0.5)
        radius = hypot(u - 0.5, v - 0.5)
        value = (1.0 + cos(angle * (2 if motif == "spiral" else 1)
                             - time_s * 2 + radius * 14 + w * pi)) / 2
    elif motif == "sparkle_field":
        # Stable pseudo-spatial pattern: no Python hash or random state.
        value = (1.0 + sin(x * 12.9898 + y * 78.233 + z * 37.719 + time_s * 5)) / 2
        value = value ** 8
    else:
        raise ValueError(f"Unsupported motif: {motif}")
    return max(0.0, min(1.0, value * energy))
